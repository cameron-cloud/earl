// Self test for scripts/bump-version.mjs, run with the Node test runner:
//
//   node --test scripts/bump-version.selftest.mjs
//
// Each case copies the script into a fresh temp directory next to fixture
// copies of the four version files, written with LF or CRLF line endings, and
// runs it the way CI and release.yml do. A Windows checkout has CRLF files
// (Git for Windows defaults to core.autocrlf=true and the repo has no
// .gitattributes), so both endings must work.

import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { after, describe, test } from "node:test";
import { fileURLToPath } from "node:url";

const script = join(dirname(fileURLToPath(import.meta.url)), "bump-version.mjs");
const scratch = mkdtempSync(join(tmpdir(), "earl-bump-version-"));
after(() => rmSync(scratch, { recursive: true, force: true }));

const fixtures = (version, lockVersion = version) => ({
  "package.json": `{
  "name": "earl",
  "private": true,
  "version": "${version}",
  "type": "module"
}
`,
  "package-lock.json": `{
  "name": "earl",
  "version": "${version}",
  "lockfileVersion": 3,
  "requires": true,
  "packages": {
    "": {
      "name": "earl",
      "version": "${version}"
    }
  }
}
`,
  "src-tauri/Cargo.toml": `[workspace]
members = [".", "crates/earl-core"]

[package]
name = "earl"
version = "${version}"
edition = "2021"

[dependencies]
serde = { version = "1", features = ["derive"] }
`,
  "src-tauri/Cargo.lock": `# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "earl"
version = "${lockVersion}"
dependencies = [
 "earl-core",
]

[[package]]
name = "earl-core"
version = "0.1.0"
`,
});

let caseNumber = 0;

function project(eol, files) {
  caseNumber += 1;
  const root = join(scratch, `case-${caseNumber}`);
  mkdirSync(join(root, "scripts"), { recursive: true });
  mkdirSync(join(root, "src-tauri"), { recursive: true });
  copyFileSync(script, join(root, "scripts", "bump-version.mjs"));
  for (const [name, text] of Object.entries(files)) {
    writeFileSync(join(root, name), text.replace(/\n/g, eol));
  }
  return root;
}

function run(root, arg) {
  const result = spawnSync(process.execPath, [join(root, "scripts", "bump-version.mjs"), arg], {
    encoding: "utf8",
  });
  return { status: result.status, output: `${result.stdout}${result.stderr}` };
}

const readText = (root, name) => readFileSync(join(root, name), "utf8");

for (const [label, eol] of [
  ["LF", "\n"],
  ["CRLF", "\r\n"],
]) {
  describe(`${label} checkout`, () => {
    test("--check passes when every version agrees", () => {
      const root = project(eol, fixtures("1.0.0"));
      const { status, output } = run(root, "--check");
      assert.equal(status, 0, output);
      assert.match(output, /All version fields agree: 1\.0\.0/);
    });

    test("--check fails and names the file when Cargo.lock disagrees", () => {
      const root = project(eol, fixtures("1.0.0", "0.9.0"));
      const { status, output } = run(root, "--check");
      assert.equal(status, 1, output);
      assert.match(output, /src-tauri\/Cargo\.lock has 0\.9\.0, package\.json has 1\.0\.0/);
    });

    test("a bump sets every file and keeps the line endings", () => {
      const root = project(eol, fixtures("1.0.0"));
      const { status, output } = run(root, "2.0.0-preview.3");
      assert.equal(status, 0, output);

      const expected = fixtures("2.0.0-preview.3");
      for (const name of Object.keys(expected)) {
        assert.equal(readText(root, name), expected[name].replace(/\n/g, eol), name);
      }
      assert.equal(run(root, "--check").status, 0);
    });
  });
}

test("a missing Cargo.lock entry is a clean error, and nothing is written", () => {
  const files = fixtures("1.0.0");
  files["src-tauri/Cargo.lock"] = files["src-tauri/Cargo.lock"].replace(
    'name = "earl"\n',
    'name = "earl-app"\n',
  );
  const root = project("\r\n", files);
  const { status, output } = run(root, "2.0.0");
  assert.equal(status, 1, output);
  assert.match(output, /^bump-version: could not find the version in Cargo\.lock$/m);
  assert.equal(readText(root, "package.json"), files["package.json"].replace(/\n/g, "\r\n"));
});

test("a version that is not semver is refused", () => {
  const root = project("\n", fixtures("1.0.0"));
  const { status, output } = run(root, "v2");
  assert.equal(status, 1, output);
  assert.match(output, /Not a semver version: v2/);
});
